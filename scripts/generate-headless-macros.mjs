#!/usr/bin/env node
/** Derive the native macro runtime from the browser authority; never reimplement its parser. */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
export function generateHeadlessMacros({ check = false } = {}) {
    const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
    const target = path.join(root, 'src/headless/macro-runtime/generated');
    const files = new Map();
    const sources = new Map();
    const prefix = '// Generated by scripts/generate-headless-macros.mjs. Edit the upstream source or adapter, then regenerate.\n';
    function source(name) {
        const data = fs.readFileSync(path.join(root, name), 'utf8');
        sources.set(name, crypto.createHash('sha256').update(data).digest('hex'));
        return data;
    }
    function fn(file, name) {
        const data = source(file);
        const match = new RegExp(`^(?:export )?function ${name}\\(`, 'm').exec(data);
        if (!match) throw new Error(`Missing authoritative function ${name}`);
        const end = data.indexOf('\n}', match.index);
        if (end < 0) throw new Error(`Unbounded authoritative function ${name}`);
        // These selected top-level functions have column-zero closing braces.
        const text = data.slice(match.index, end + 2);
        return text.startsWith('export ') ? text : `export ${text}`;
    }
    function imports(data, replacements) {
        return data.replace(/^import ([\s\S]*?) from ['"]([^'"]+)['"];$/gm, (whole, names, spec) => {
            const destination = replacements(spec);
            if (!destination) throw new Error(`Unmapped macro import ${spec}`);
            return `import ${names} from '${destination}';`;
        });
    }
    const engines = ['MacroLexer', 'MacroParser', 'MacroRegistry', 'MacroEngine', 'MacroFlags', 'MacroCstWalker', 'MacroEnvBuilder', 'MacroEnv.types'];
    for (const name of engines) {
        const data = source(`public/scripts/macros/engine/${name}.js`);
        let mapped = imports(data, spec => spec.startsWith('./') || spec.startsWith('../definitions/') ? spec : '../../platform.js');
        if (/console\./.test(mapped)) mapped = 'import { macroConsole as console } from \'../../platform.js\';\n' + mapped;
        if (name === 'MacroCstWalker') mapped = 'import { SillyTavern } from \'../../platform.js\';\n' + mapped;
        files.set(`engine/${name}.js`, prefix + mapped);
    }
    const definitions = ['core', 'env', 'state', 'chat', 'time', 'variable', 'instruct'];
    for (const name of definitions) {
        let data = imports(source(`public/scripts/macros/definitions/${name}-macros.js`), spec => spec.startsWith('../engine/') ? spec : '../../platform.js');
        const explicit = name === 'core' || name === 'chat' ? 'document' : name === 'variable' ? 'SillyTavern' : '';
        if (/console\./.test(data)) data = 'import { macroConsole as console } from \'../../platform.js\';\n' + data;
        if (explicit) data = `import { ${explicit} } from '../../platform.js';\n` + data;
        files.set(`definitions/${name}-macros.js`, prefix + data);
    }
    files.set('engine/MacroDiagnostics.js', prefix + 'export { createMacroRuntimeError, logMacroRuntimeWarning, logMacroInternalError, logMacroRegisterWarning, logMacroRegisterError, logMacroGeneralError, logMacroSyntaxWarning } from \'../../platform.js\';\n');
    files.set('system.js', prefix + source('public/scripts/macros/macro-system.js'));
    let legacy = imports(source('public/scripts/macros.js'), spec => spec === './macros/macro-system.js' ? './system.js' : '../platform.js');
    legacy = 'import { $, document, macroConsole as console } from \'../platform.js\';\n' + legacy;
    files.set('legacy.js', prefix + legacy);
    const variableNames = ['getLocalVariable', 'setLocalVariable', 'getGlobalVariable', 'setGlobalVariable', 'addLocalVariable', 'addGlobalVariable', 'incrementLocalVariable', 'incrementGlobalVariable', 'decrementLocalVariable', 'decrementGlobalVariable', 'resolveVariable', 'getVariableMacros', 'existsLocalVariable', 'existsGlobalVariable', 'deleteLocalVariable', 'deleteGlobalVariable'];
    files.set('variables.js', prefix + 'import { chat_metadata, extension_settings, saveSettingsDebounced, saveMetadataDebounced, convertValueType, validateVariableIndex, macroConsole as console } from \'../platform.js\';\n' + variableNames.map(name => {
        const body = fn('public/scripts/variables.js', name);
        return ['setLocalVariable', 'setGlobalVariable'].includes(name)
            ? body.replace('\n', '\n    validateVariableIndex(args);\n') : body;
    }).join('\n\n'));
    const utils = ['getStringHash', 'isTrueBoolean', 'isFalseBoolean', 'convertValueType', 'timestampToMoment', 'parseTimestamp', 'isDigitsOnly', 'escapeRegex', 'uuidv4'];
    files.set('utils.js', prefix + 'import { moment, getCurrentLocale, SlashCommandClosure, crypto } from \'../platform.js\';\nconst dateCache = new Map();\n' + utils.map(name => fn('public/scripts/utils.js', name)).join('\n\n') + '\nexport function resetNativeDateCache() { dateCache.clear(); }\n');
    const scriptFns = ['baseChatReplace', 'createLazyFields', 'getCharacterCardFieldsLazy', 'getCharacterCardFields', 'parseMesExamples', 'substituteParamsLegacy', 'substituteParams', 'getMaxContextTokens', 'getMaxResponseTokens', 'getMaxPromptTokens'];
    files.set('script.js', prefix + 'import { power_user, chat_metadata, characters, this_chid, selected_group, groups, name1, name2, main_api, oai_settings, max_context, amount_gen, nai_settings, getKayraMaxContextTokens, getGroupCharacterCardsLazy, collapseNewlines, getGeneratingModel, accountStorage, onboardingExperimentalMacroEngine, MacroEngine, MacroEnvBuilder } from \'../platform.js\';\nimport { evaluateMacros } from \'./legacy.js\';\nimport { formatInstructModeExamples } from \'./instruct.js\';\n' + scriptFns.map(name => fn('public/script.js', name)).join('\n\n'));
    files.set('instruct.js', prefix + 'import { power_user, selected_group, name1, name2, getGroupNames } from \'../platform.js\';\nimport { substituteParams } from \'./script.js\';\nconst names_behavior_types = { NONE:\'none\', FORCE:\'force\', ALWAYS:\'always\' };\n' + ['formatInstructModeExamples', 'getInstructMacros'].map(name => fn('public/scripts/instruct-mode.js', name)).join('\n\n') + '\n\n' + fn('public/scripts/openai.js', 'parseExampleIntoIndividual'));
    const manifest = { version: 1, sources: Object.fromEntries([...sources].sort()), files: Object.fromEntries([...files].map(([name, text]) => [name, crypto.createHash('sha256').update(text).digest('hex')])) };
    files.set('manifest.json', JSON.stringify(manifest, null, 2) + '\n');
    for (const [name, data] of files) {
        const file = path.join(target, name);
        if (check) { if (!fs.existsSync(file) || fs.readFileSync(file, 'utf8') !== data) throw new Error(`Native macro source is stale: ${name}`); } else { fs.mkdirSync(path.dirname(file), { recursive: true }); fs.writeFileSync(file, data); }
    }
    console.log(`${check ? 'Verified' : 'Generated'} ${files.size} native macro source files from ${sources.size} upstream files.`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) generateHeadlessMacros({ check: process.argv.includes('--check') });
