#!/usr/bin/env node
/**
 * SillyTavern headless companion entry for the Messenger Android front-end.
 *
 * This is NOT the full SillyTavern server. It mounts only the versioned
 * `/api/v1` contract, binds strictly to 127.0.0.1, and requires a scoped
 * bearer capability on every request. It exists so a native client can use
 * SillyTavern as a *backend* without driving the browser SPA, without a
 * cookie/session login WebView, and without exposing the private `/api/*`
 * SPA routes.
 *
 * Security model (must not be weakened):
 *  - Loopback bind only. The companion APK and the Messenger APK have separate
 *    UIDs; the TCP socket is the IPC boundary, so binding 0.0.0.0 would expose
 *    every user's chats and provider keys to the LAN.
 *  - A 32-byte random capability token, passed by the companion over a
 *    signature-protected AIDL call, is printed once to stdout (never logged
 *    in a URL, file or error message) and compared in constant time.
 *  - No static file serving, no SPA, no CORS, no CSRF cookie flow. All state
 *    changes require the bearer token; GET also requires it so an unrelated
 *    local process cannot enumerate characters.
 *  - Provider API keys stay inside the user's `secrets.json` and are only ever
 *    attached to the outbound provider request; they never enter a response.
 *
 * Usage (invoked by the companion, not by a human):
 *   node src/headless-companion.js --dataRoot <dir> --port <port> --token <hex>
 */
import crypto from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';

/**
 * Parses the tiny companion-specific argv. No yargs dependency is needed: this
 * process is launched programmatically with a fixed argv shape.
 * @param {string[]} argv Command-line arguments
 * @returns {{dataRoot: string, port: number, token: string}} Parsed options
 */
function parseArgs(argv) {
    const options = {};
    for (let i = 0; i < argv.length; i++) {
        if (!argv[i].startsWith('--')) continue;
        const key = argv[i].slice(2);
        const value = argv[i + 1];
        if (value === undefined || value.startsWith('--')) throw new Error(`Missing value for --${key}`);
        options[key] = value;
        i++;
    }
    if (!options.dataRoot) throw new Error('--dataRoot is required');
    if (!options.token || !/^[0-9a-f]{64}$/.test(options.token)) throw new Error('--token must be 64 lowercase hex characters');
    const port = Number(options.port ?? 0);
    if (!Number.isInteger(port) || port < 0 || port > 65535) throw new Error('--port must be a valid port (0 = ephemeral)');
    return { dataRoot: path.resolve(options.dataRoot), port, token: options.token };
}

/**
 * Writes the companion-owned config.yaml BEFORE importing any ST module.
 * Several ST modules read config at module-evaluation time, so setConfigFilePath
 * must run before the first dynamic import() below.
 * @param {string} dataRoot Root directory
 * @returns {string} Config file path
 */
function prepareConfig(dataRoot) {
    fs.mkdirSync(dataRoot, { recursive: true });
    const configPath = path.join(dataRoot, 'config.yaml');
    if (!fs.existsSync(configPath)) {
        fs.writeFileSync(configPath, [
            '# Generated by the Messenger SillyTavern companion. Do not edit.',
            'dataRoot: ' + JSON.stringify(dataRoot),
            'listen: false',
            'whitelistMode: true',
            'whitelist:',
            '  - 127.0.0.1',
            '  - ::1',
            'enableUserAccounts: false',
            'basicAuthMode: false',
            'disableCsrfProtection: false',
            'api:',
            '  v1:',
            '    enabled: true',
            '    headlessPlugins: false',
            '',
        ].join('\n'), 'utf8');
    }
    return configPath;
}

async function main() {
    const { dataRoot, port, token } = parseArgs(process.argv.slice(2));
    const configPath = prepareConfig(dataRoot);

    // Order matters: util.js holds the config path, and users.js/secrets.js read
    // config during evaluation. Import util first and set the path, then the rest.
    // globalThis.DATA_ROOT is required by several ST modules at evaluation time.
    globalThis.DATA_ROOT = dataRoot;
    const { setConfigFilePath } = await import('./util.js');
    setConfigFilePath(configPath);
    process.env.SILLYTAVERN_API_V1_ENABLED = 'true';
    process.env.SILLYTAVERN_COMPANION_MODE = 'true';

    const [expressModule, apiModule, constants] = await Promise.all([
        import('express'),
        import('./endpoints/api-v1.js'),
        import('./constants.js'),
    ]);
    const express = expressModule.default;
    const apiV1Router = apiModule.router;
    const { DEFAULT_USER, USER_DIRECTORY_TEMPLATE } = constants;

    /** Build the canonical user directory map inside the companion's data root. */
    /** @type {Record<string, string>} */
    const dirs = {};
    for (const [key, relative] of Object.entries(USER_DIRECTORY_TEMPLATE)) {
        dirs[key] = key === 'root' ? dataRoot : path.join(dataRoot, DEFAULT_USER.handle, relative);
    }
    for (const dir of Object.values(dirs)) fs.mkdirSync(dir, { recursive: true });

    const tokenBytes = Buffer.from(token, 'hex');
    const app = express();
    app.disable('x-powered-by');

    app.use((request, response, next) => {
        const header = request.get('authorization') ?? '';
        const presented = header.startsWith('Bearer ') ? header.slice(7) : '';
        // The capability is 64 hex characters; compare the decoded 32 bytes,
        // not the UTF-8 text, so both buffers have the same length.
        const presentedBytes = /^[0-9a-f]{64}$/.test(presented)
            ? Buffer.from(presented, 'hex')
            : Buffer.alloc(0);
        if (presentedBytes.length !== tokenBytes.length || !crypto.timingSafeEqual(presentedBytes, tokenBytes)) {
            response.status(401).json({ error: { code: 'unauthorized', message: 'Invalid companion capability.', retryable: false, requestId: '' } });
            return;
        }
        // CSRF is meaningless for a bearer-authenticated, non-cookie client.
        // Populate a stable session + CSRF token so shared ST middleware and the
        // WebView shell's getRequestHeaders() keep working without a login flow.
        request.session ??= {};
        request.session.handle = DEFAULT_USER.handle;
        request.session.csrfToken ??= token.slice(0, 32);
        request.user = { profile: DEFAULT_USER, directories: dirs };
        next();
    });
    // Authenticate before accepting a bounded character-image import body.
    app.use(express.json({ limit: '8mb' }));

    // Non-cookie CSRF bypass for API v1 mutations. The bearer check above is
    // strictly stronger: a cross-origin page cannot read the random token.
    app.use((request, _response, next) => {
        request.headers['x-csrf-token'] = request.session?.csrfToken ?? '';
        next();
    });

    app.get('/api/v1/companion/health', (_request, response) => {
        response.json({ ok: true, service: 'messenger-sillytavern', version: 1, headless: true });
    });
    app.use('/api/v1', apiV1Router);

    // Everything else is deliberately unavailable in companion mode.
    app.use((_request, response) => {
        response.status(404).json({ error: { code: 'not_found', message: 'Only /api/v1 is available in companion mode.', retryable: false, requestId: '' } });
    });

    app.use((error, _request, response, _next) => {
        console.error('[companion] request failed:', error?.message ?? error);
        response.status(500).json({ error: { code: 'internal', message: 'Companion request failed.', retryable: false, requestId: '' } });
    });

    const server = await new Promise((resolve, reject) => {
        const instance = app.listen(port, '127.0.0.1', () => resolve(instance));
        instance.once('error', reject);
    });

    const actualPort = server.address().port;
    // The single, machine-readable handshake line. The companion reads this
    // from stdout and passes port + token to the main app over signature-AIDL.
    console.log(JSON.stringify({ type: 'companion_ready', port: actualPort, token }));
    console.error(`[companion] SillyTavern headless API listening on 127.0.0.1:${actualPort}`);

    const shutdown = () => {
        server.close(() => process.exit(0));
        setTimeout(() => process.exit(1), 5000).unref();
    };
    process.on('SIGTERM', shutdown);
    process.on('SIGINT', shutdown);
}

main().catch(error => {
    console.error('[companion] failed to start:', error?.message ?? error);
    process.exit(1);
});
